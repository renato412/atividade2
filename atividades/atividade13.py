dia = int(input("informe o dia da semana: "))

if dia == 1:
    print("segunda")

elif dia == 2:
    print("terça-feira")

elif dia == 3:
    print("quanta-feiea")

elif dia == 4:
    print("quinta-feira")

elif dia == 5:
    print("sexta-feira")

elif dia == 6:
    print("sabádo")

elif dia == 7:
    print("domingo")

else:
    print("numero ivalido")